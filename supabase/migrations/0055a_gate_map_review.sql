-- 0055a — Gate map REVIEW (read-only). Run this FIRST.
--
-- Matches the handwritten gate-number list (names_list_v2.txt) against
-- current gym_subscriptions members by normalized name and reports, per
-- file entry, the recommended action. NOTHING is written by this script.
--
-- Buckets:
--   ALREADY_MAPPED  — this gate number OR this member is already in anviz_member_map
--   EXACT_INSERT    — exactly one subscriber matches the name exactly -> safe to insert
--   AMBIGUOUS_EXACT — name matches >1 distinct subscriber -> pick by hand
--   CLOSE_REVIEW    — best fuzzy match >= 0.45 but not exact -> "زين حيدر" vs "زين معن حيدر"
--   NO_MATCH        — no subscriber resembles this name
--
-- The 28 duplicate device IDs (255–310, two handwriting readings) are NOT
-- in this list — they were excluded as unresolved conflicts.
-- ============================================================
create extension if not exists pg_trgm;

-- Normalization for Arabic name matching:
--   • strip diacritics + tatweel
--   • fold alef variants -> ا, ى/ئ -> ي, ؤ -> و, ة -> ه
--   • lowercase, trim, collapse internal whitespace
-- Inlined as a CTE-friendly expression via the helper function below.
create or replace function public.gate_norm(x text) returns text
language sql immutable as $$
  select regexp_replace(
           translate(
             lower(btrim(regexp_replace(coalesce(x,''), '[ًٌٍَُِّْـ]', '', 'g'))),
             'أإآٱىئؤة', 'ااااييوه'
           ),
           '\s+', ' ', 'g'
         );
$$;

